"""Build try/data.js for the hosted no-install example.

Bundles every customer that triggered a rule (flags, evidence, templated case summary and
detection-window timeline), using the app's own detection code, so the hosted example
ranks exactly like the app.

    python try/build_data.py && node try/test_score.js
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app"))

import data_sources  # noqa: E402
import detection  # noqa: E402


def main():
    d = detection.prepare(data_sources.sample_frames())
    flags = detection.evaluate(d)
    scored = detection.score(flags)
    custs = []
    for _, r in flags.iterrows():
        tl = detection.timeline(d, r["customer_id"])
        tl = tl[tl["ts"] >= detection.WINDOW_START]
        custs.append({
            "customer_id": r["customer_id"], "customer_name": r["customer_name"], "segment": r["segment"],
            "home_city": r["home_city"], "confirmed_ato": bool(r["confirmed_ato"]),
            "flags": {k: int(r[k]) for k in detection.RULES}, "why": {k: r[f"{k}_why"] for k in detection.RULES if r[k]},
            "summary": detection.case_summary(r),
            "timeline": [[t.ts.strftime("%b %d %H:%M:%S"), t.type, t.detail, t.session] for t in tl.itertuples()],
        })
    total = int(d["customers"]["confirmed_ato"].sum())
    data = {
        "window": "2 October to 1 November 2026", "totalAto": total, "rules": detection.RULES, "labels": detection.LABELS,
        "weights": detection.DEFAULT_WEIGHTS, "threshold": detection.DEFAULT_THRESHOLD, "customers": custs,
        # Reference results at default weights, used by try/test_score.js.
        "check": {"order": scored["customer_id"].tolist(),
                  "perf": {str(t): json.loads(detection.rule_performance(scored, t, total).to_json(orient="records"))
                           for t in (40, 60)}},
    }
    out = ROOT / "try" / "data.js"
    out.write_text("// Generated by try/build_data.py from synthetic data. Do not edit.\nwindow.ATO_DATA = "
                   + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB, {len(custs)} customers)")


if __name__ == "__main__":
    main()
