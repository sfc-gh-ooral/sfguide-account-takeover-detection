import streamlit as st

import common
import data_sources as ds
import detection

ctx = common.context()
scored, data = ctx["scored"], ctx["data"]

st.title("Case timeline")
ids = scored["customer_id"].tolist()
default = st.session_state.get("customer_id", ids[0])
names = dict(zip(scored["customer_id"], scored["customer_name"]))
ranks = dict(zip(scored["customer_id"], scored["alert_rank"]))
cid = st.selectbox("Customer", ids, index=ids.index(default) if default in ids else 0,
                   format_func=lambda c: f"#{ranks[c]} · {c} · {names[c]}")
st.session_state.customer_id = cid
row = scored[scored["customer_id"] == cid].iloc[0]

with st.container(horizontal=True):
    st.metric("Rank", f"#{int(row['alert_rank'])} of {len(scored):,}", border=True)
    st.metric("Alert score", int(row["alert_score"]), border=True)
    st.metric("Rules triggered", int(row["rules_fired"]), border=True)
    st.metric("Home", f"{row['home_city']} · {row['segment']}", border=True)

left, right = st.columns([2, 3])
with left:
    with st.container(border=True):
        st.subheader("Case summary")
        text, live_text = None, False
        if ctx["live"]:
            try:
                s = ds.live_summaries()
                hit = s[s["customer_id"] == cid]
                if len(hit):
                    text, live_text = hit.iloc[0]["case_summary"], True
            except Exception as exc:
                st.caption(f"Could not read CASE_SUMMARIES: {exc}")
        if live_text:
            st.badge("Generated by Snowflake Cortex AI_COMPLETE", icon=":material/bolt:", color="blue")
            st.markdown(text)
        else:
            st.badge("Sample AI response", icon=":material/info:", color="orange")
            st.markdown(detection.case_summary(row))
            if ctx["live"]:
                st.caption("Live summaries are generated for the top 20 alerts only.")
        st.caption("Draft for an investigator to review. It does not decide the case.")
    with st.container(border=True):
        st.subheader("Why it alerted")
        for r in detection.RULES:
            if row[r]:
                with st.container(border=True):
                    st.markdown(f"**{detection.LABELS[r]}** · {int(common.weights()[r])} points")
                    st.caption(row[f"{r}_why"])

with right:
    with st.container(border=True):
        st.subheader("Activity in the detection window")
        tl = detection.timeline(data, cid)
        tl = tl[tl["ts"] >= detection.WINDOW_START].iloc[::-1]
        st.dataframe(tl[["ts", "type", "detail", "session"]], hide_index=True, height=560,
                     alt="Logins, MFA events, account changes and transfers for this customer in time order",
                     column_config={"ts": st.column_config.DatetimeColumn("Time", format="MMM D, HH:mm:ss"),
                                    "type": "Event", "detail": "Detail", "session": "Session"})
        st.caption("Identity events, account changes and transfers, joined in time order, most recent first.")
